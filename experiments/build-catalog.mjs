import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {settingsSchema,settingGroups,validateSettings} from '../little-mouse/public/settings.js';
const root=new URL('../',import.meta.url), annotations=JSON.parse(await readFile(new URL('variables.json',import.meta.url)));
const check=process.argv.includes('--check');
const keys=Object.keys(settingsSchema);
if(keys.length!==Object.keys(annotations).length||keys.some(k=>!annotations[k])||Object.keys(annotations).some(k=>!settingsSchema[k]))throw Error('Catalog must cover every setting exactly once');
for(const [key,a] of Object.entries(annotations)){
 if(!a.hypothesis||!['1','2','3','E'].includes(a.stage)||a.evidence!=='design-hypothesis'||a.automaticLearningEligible!==false)throw Error('Invalid annotation '+key);
 if(!a.interactions.length||a.interactions.some(k=>!settingsSchema[k]))throw Error('Unknown interaction '+key);
 if(!a.measurements.length||a.measurements.some(k=>!['tracking','contact','exposure','performance','motion','return','reacquisition','geometry','audio'].includes(k)))throw Error('Unknown measurement '+key);
}
const schemaHash=createHash('sha256').update(JSON.stringify(settingsSchema)).digest('hex');
const catalog={catalogVersion:1,status:'proposed-not-running',settingsSchemaHash:schemaHash,variables:keys.map(id=>({id,...settingsSchema[id],...annotations[id]}))};
async function emit(path,content){const url=new URL(path,root);if(check){if(await readFile(url,'utf8')!==content)throw Error('Stale generated file '+path);}else await writeFile(url,content);}
await mkdir(new URL('docs/experiments/',root),{recursive:true});
await emit('experiments/catalog.json',JSON.stringify(catalog,null,2)+'\n');
const recordSchema=JSON.parse(await readFile(new URL('record.schema.json',import.meta.url)));
recordSchema.$defs.settings={type:'object',additionalProperties:false,required:keys,properties:Object.fromEntries(keys.map(k=>{
 const s=settingsSchema[k];
 return [k,s.type==='number'?{type:k==='count'?'integer':'number',minimum:s.min,maximum:s.max}:s.options?{enum:s.options.map(o=>o.value)}:s.type==='color'?{type:'string',pattern:'^#[0-9a-fA-F]{6}$'}:{type:'boolean'}];
}))};
await emit('experiments/record.schema.json',JSON.stringify(recordSchema,null,2)+'\n');

for(const [group,title] of Object.entries(settingGroups)){
 const lines=[`# ${title}: experiment variables`,'','Generated by `node experiments/build-catalog.mjs`; edit `experiments/variables.json` for hypotheses.',
 'Defaults and allowed ranges come directly from `public/settings.js`; these are software bounds, not approved trial ranges.',
 'All effects below are hypotheses, not established cat preferences. Stage E is engineering-only; all automatic learning is disabled.',
 'Measurement definitions and staging: [protocol](protocol.md). Runtime applicability must be verified before each trial.','',
 '| Variable | Baseline; software domain | Potential benefit / cost | Interactions | Measures | Stage |','| --- | --- | --- | --- | --- | --- |'];
 for(const v of catalog.variables.filter(v=>v.group===group)){
 const domain=v.type==='number'?`${v.min}–${v.max}; step ${v.step} ${v.unit||''}`:v.options?v.options.map(x=>x.value).join(', '):v.type==='boolean'?'true / false':'hex RGB';
 lines.push(`| \`${v.id}\` | ${v.default}; ${domain} | ${v.hypothesis} | ${v.interactions.join(', ')} | ${v.measurements.join(', ')} | ${v.stage} |`);
 }
 await emit(`docs/experiments/${group}.md`,lines.join('\n')+'\n');
}
const trials=JSON.parse(await readFile(new URL('trials.json',import.meta.url)));
for(const t of trials.trials){
 if(t.status!=='proposed'||t.variants.length!==2)throw Error('Invalid trial '+t.id);
 for(const v of t.variants){validateSettings(v.settings);if(Object.keys(v.settings).length!==1||!Object.hasOwn(v.settings,t.variable))throw Error('Trial must change one declared setting');}
 if(t.variants[0].settings[t.variable]!==settingsSchema[t.variable].default)throw Error('Stale baseline '+t.id);
 if(annotations[t.variable].stage==='E')throw Error('Engineering variable cannot enter cat trial');
}
console.log(`${check?'Checked':'Generated'} ${keys.length} variables, seven topic tables, ${trials.trials.length} proposed comparisons; schema ${schemaHash.slice(0,12)}`);
